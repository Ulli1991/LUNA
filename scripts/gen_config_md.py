"""Generate docs/CONFIG.md from template_config.py and the IC modules' Params.

Pure text/AST, safe anywhere: python scripts/gen_config_md.py
The tables are regenerated; the notes below NOTES_MARK in docs/CONFIG.md are
written by hand and kept.
"""
import ast
import os
import re
import sys

SRC = "src/luna/template_config.py"
IC = "src/luna/ic_generation"
OUT = "docs/CONFIG.md"
NOTES_MARK = "<!-- notes: written by hand below this line; gen_config_md.py keeps them -->"
SEC_RE = re.compile(r"#\s*-+\s*(.+?)\s*-+\s*$")


def _fields(src, cls_name):
    """[(section, name, type, default, comment)] of the dataclass `cls_name` in `src`."""
    lines = src.split("\n")
    cls = next(n for n in ast.parse(src).body
               if isinstance(n, ast.ClassDef) and n.name == cls_name)
    rows, section = [], ""
    for node in cls.body:
        if not isinstance(node, ast.AnnAssign) or not isinstance(node.target, ast.Name):
            continue
        for i in range(node.lineno - 2, cls.lineno - 1, -1):
            m = SEC_RE.search(lines[i])
            if m:
                section = m.group(1)
                break
            if re.match(r"\s*[a-zA-Z_]+\s*:", lines[i]):
                break
        line = lines[node.lineno - 1]
        comment = line.split("#", 1)[1].strip() if "#" in line else ""
        rows.append((section, node.target.id, ast.get_source_segment(src, node.annotation),
                     ast.get_source_segment(src, node.value) if node.value is not None else "",
                     comment))
    return rows


def _table(rows):
    out = ["| field | type | default | values |", "|---|---|---|---|"]
    for _s, name, typ, default, comment in rows:
        out.append(f"| `{name}` | `{typ}` | `{default.replace('|', chr(92) + '|')}` | "
                   f"{comment.replace('|', chr(92) + '|')} |")
    return out


def _problems():
    """[(module, [test_problem, ...])] for each IC module that declares Params."""
    src = open(os.path.join(IC, "ic.py")).read()
    tree = ast.parse(src)
    imports = {}
    for n in tree.body:
        if isinstance(n, ast.ImportFrom) and n.level == 1 and n.module:
            for a in n.names:
                imports[a.asname or a.name] = n.module
    reg = next(n for n in tree.body if isinstance(n, ast.Assign)
               and getattr(n.targets[0], "id", "") == "_IC_REGISTRY")
    by_mod = {}
    for k, v in zip(reg.value.keys, reg.value.values):
        mod = imports.get(v.elts[0].id)
        if mod and "class Params" in open(os.path.join(IC, mod + ".py")).read():
            by_mod.setdefault(mod, []).append(k.value)
    return sorted(by_mod.items(), key=lambda kv: kv[1][0])


def main():
    rows = _fields(open(SRC).read(), "Config")
    notes = ""
    if os.path.exists(OUT):
        old = open(OUT).read()
        if NOTES_MARK in old:
            notes = old.split(NOTES_MARK, 1)[1].strip("\n")
    md = ["# Config reference", "",
          f"The {len(rows)} fields of `Config` (`src/luna/template_config.py`) and each test "
          "problem's own parameters (`cfg.problem`, the `Params` of its IC module). Set them in "
          "a config file or a run script with `dataclasses.replace`, or on the command line as "
          "`field=value` and `problem.<name>=value`. The tables are generated by "
          "`scripts/gen_config_md.py`; the notes at the end are written by hand.", ""]
    cur = None
    for r in rows:
        if r[0] != cur:
            cur = r[0]
            md += ["", f"## {cur}", ""] + _table([x for x in rows if x[0] == cur])
    md += ["", "## Problem parameters (`cfg.problem`)", "",
           "`test_problem` picks the IC; its module's `Params` holds the IC's own numbers, "
           "defaults included. A problem not listed has none.", ""]
    for mod, names in _problems():
        prows = _fields(open(os.path.join(IC, mod + ".py")).read(), "Params")
        md += [f"### {', '.join(names)} (`luna/ic_generation/{mod}.py`)", ""] + _table(prows) + [""]
    md += [NOTES_MARK, "", notes, ""]
    text = "\n".join(md).replace("\n\n\n", "\n\n")
    open(OUT, "w").write(text)
    print(f"wrote {OUT}: {len(rows)} Config fields, {len(_problems())} problem modules")


if __name__ == "__main__":
    sys.exit(main())
