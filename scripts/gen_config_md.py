"""Generate docs/CONFIG.md from template_config.py (fields, defaults, comments).

Pure text/AST — safe anywhere: python scripts/gen_config_md.py
Rerun after adding/annotating config fields.
"""
import ast
import re
import sys

SRC = "template_config.py"
OUT = "docs/CONFIG.md"


def main():
    src = open(SRC).read()
    lines = src.split("\n")
    tree = ast.parse(src)
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef))

    rows, section = [], "General"
    sec_re = re.compile(r"#\s*-+\s*(.+?)\s*-+\s*$")
    for node in cls.body:
        if not isinstance(node, ast.AnnAssign) or not isinstance(node.target, ast.Name):
            continue
        # nearest section banner above this field
        for i in range(node.lineno - 2, -1, -1):
            m = sec_re.search(lines[i])
            if m and m.group(1).strip("- "):
                section = m.group(1)
                break
            if re.match(r"\s*[a-zA-Z_]+\s*:", lines[i]):
                break
        name = node.target.id
        typ = ast.get_source_segment(src, node.annotation)
        default = (ast.get_source_segment(src, node.value)
                   if node.value is not None else "")
        # trailing comment on the field's line(s), else full-line comment above
        comment = ""
        for ln in range(node.lineno - 1, node.end_lineno):
            if "#" in lines[ln]:
                comment = lines[ln].split("#", 1)[1].strip()
                break
        if not comment and node.lineno >= 2:
            above = lines[node.lineno - 2].strip()
            if above.startswith("#") and not sec_re.search(above):
                comment = above.lstrip("# ").strip()
        rows.append((section, name, typ, default, comment))

    n_doc = sum(1 for r in rows if r[4])
    md = ["# Config reference",
          "",
          f"All {len(rows)} fields of the `Config` dataclass "
          "(`template_config.py`; copy to `config.py` or override via "
          "`dataclasses.replace` in a run script). "
          f"Generated by `scripts/gen_config_md.py` — do not edit by hand. "
          f"{n_doc}/{len(rows)} fields carry a comment; undocumented ones "
          "show an empty description (add the comment in the template and "
          "regenerate).",
          ""]
    cur = None
    for section, name, typ, default, comment in rows:
        if section != cur:
            cur = section
            md += [f"## {section}", "", "| field | type | default | description |",
                   "|---|---|---|---|"]
        d = default.replace("|", "\\|")
        c = comment.replace("|", "\\|")
        md.append(f"| `{name}` | `{typ}` | `{d}` | {c} |")
        if name == rows[-1][1] and section == rows[-1][0]:
            pass
    # blank line after each table
    out, prev_sec = [], None
    for line in md:
        if line.startswith("## ") and prev_sec is not None:
            out.append("")
        out.append(line)
        if line.startswith("## "):
            prev_sec = line
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(rows)} fields, {n_doc} documented")


if __name__ == "__main__":
    sys.exit(main())
